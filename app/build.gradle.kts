val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
val hasReleaseKeystore = run {
    if (!keystorePropertiesFile.exists()) {
        return@run false
    }
    keystorePropertiesFile.inputStream().use { input ->
        keystoreProperties.load(input.reader().readText().removePrefix("\uFEFF").reader())
    }
    val storeFilePath = keystoreProperties.getProperty("storeFile")?.trim().orEmpty()
    storeFilePath.isNotEmpty() && rootProject.file(storeFilePath).exists()
}

